test('service worker reuses unchanged files from the previous release and refetches changed ones', async () => {
  const unchanged = new Response('unchanged');
  const worker = loadServiceWorker({
    precacheUrls: ['./same.js', './changed.js', './new.js'],
    integrity: {
      './same.js': sriOf('unchanged'),
      './changed.js': sriOf('new bytes'),
      './new.js': sriOf('added')
    },
    previousCaches: {
      'effetune-v1-old': {
        './same.js': unchanged,
        './changed.js': new Response('old bytes')
      }
    }
  });

  await install(worker);

  assert.deepEqual(worker.fetchCalls.map(request => request.url).sort(), ['./changed.js', './new.js']);
  const stored = new Map(worker.putCalls);
  assert.equal(stored.get('./same.js'), unchanged);
  assert.equal(await stored.get('./same.js').text(), 'unchanged');
  assert.equal(stored.get('./changed.js').name, './changed.js');
});


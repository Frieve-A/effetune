import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { parseSfz } from '../js/sfz/parser.js';
import { packSfzAsset } from '../js/sfz/asset.js';
import { createSfzGeneratorSample } from '../js/sfz/generators.js';
import { prepareSfzOscillatorSources } from '../js/sfz/oscillator-source.js';

const sources = Object.freeze({
  DelaySamples: '<region> sample=constant.wav key=60 delay_samples=240 ampeg_release=.001',
  Beats: '<region> sample=constant.wav key=60 loop_mode=loop_continuous delay_beats=.01 stop_beats=.03 ampeg_release=.001',
  Repeats: '<region> sample=constant.wav key=60 count=3',
  Reverse: '<region> sample=ramp.wav key=60 reverse_locc2=64 reverse_hicc2=127',
  Alternate: '<region> sample=ramp.wav key=60 loop_mode=loop_continuous loop_start=32 loop_end=63 loop_type=alternate sample_quality=1',
  Pedal: '<region> sample=constant.wav key=60 loop_mode=loop_continuous sustain_cc=1 sustain_lo=1 ampeg_release=.001',
  Controller: '<region> sample=constant.wav key=-1 loop_mode=loop_continuous on_lohdcc1=.5 on_hihdcc1=.6 stop_locc2=64',
  Silent: '<region> sample=constant.wav key=60 loop_mode=loop_continuous off_by=3 off_time=.001 ' +
    '<region> sample=unneeded.wav key=61 group=3 end=-1'
});

export async function generateSfzPlaybackFixture({ check = false } = {}) {
  const declarations = [];
  for (const [name, source] of Object.entries(sources)) {
    let parsed = await parseSfz({ selectedPath: 'playback.sfz', readText: async () => source, onDiagnostic: null });
    assert.deepEqual(parsed.modulation.diagnostics, []);
    const samples = new Map([
      ['constant.wav', { sampleRate: 48000, channels: [new Float32Array(128).fill(.25)] }],
      ['ramp.wav', { sampleRate: 48000, channels: [Float32Array.from({ length: 128 }, (_, i) => i / 512)] }],
      ['*silence', createSfzGeneratorSample('*silence')]
    ]);
    const prepared = await prepareSfzOscillatorSources(parsed, async path => samples.get(path), 1048576);
    parsed = prepared.parsed;
    for (const [path, pcm] of prepared.samples) samples.set(path, pcm);
    const asset = packSfzAsset(parsed.regions, samples, { modulation: parsed.modulation });
    const bytes = new Uint8Array(asset.payload), lines = [];
    for (let i = 0; i < bytes.length; i += 24) lines.push('  ' + [...bytes.subarray(i, i + 24)].join(', ') + ',');
    declarations.push(`inline constexpr std::uint32_t kPlayback${name}Footprint = ${asset.footprintBytes}u;\n` +
      `inline constexpr std::array<std::uint8_t, ${bytes.length}> kPlayback${name}Payload{\n${lines.join('\n')}\n};`);
  }
  const result = '// Generated by tools/generate-sfz-playback-fixture.mjs from the production parser and serializer.\n' +
    '#pragma once\n#include <array>\n#include <cstdint>\n// clang-format off\n' + declarations.join('\n') + '\n// clang-format on\n';
  const destination = new URL('../dsp/plugins/others/soundfont_player/playback_fixture.h', import.meta.url);
  if (check) assert.equal((await fs.readFile(destination, 'utf8')).replaceAll('\r\n', '\n'), result);
  else await fs.writeFile(destination, result);
}
if (process.argv[1]?.endsWith('generate-sfz-playback-fixture.mjs'))
  await generateSfzPlaybackFixture({ check: process.argv.includes('--check') });

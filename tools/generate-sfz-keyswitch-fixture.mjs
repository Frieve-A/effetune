import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { parseSfz } from '../js/sfz/parser.js';
import { packSfzAsset } from '../js/sfz/asset.js';
export async function generateSfzKeyswitchFixture({ check = false } = {}) {
  const source = '<global> sample=constant.wav amp_veltrack=0 loop_mode=loop_continuous ' +
    '<region> lochan=1 hichan=1 sw_lokey=24 sw_hikey=26 sw_default=24 sw_last=24 ' +
    '<region> lochan=2 hichan=2 sw_lokey=36 sw_hikey=38 sw_default=36 sw_last=36';
  const parsed = await parseSfz({ selectedPath: 'switches.sfz', readText: async () => source, onDiagnostic: null });
  assert.deepEqual(parsed.modulation.diagnostics, []);
  const asset = packSfzAsset(parsed.regions, new Map([['constant.wav', { sampleRate: 48000, channels: [new Float32Array(64).fill(.1)] }]]), { modulation: parsed.modulation });
  const bytes = new Uint8Array(asset.payload), lines = [];
  for (let index = 0; index < bytes.length; index += 24) lines.push('  ' + [...bytes.subarray(index, index + 24)].join(', ') + ',');
  const output = '#pragma once\n#include <array>\n#include <cstdint>\n// Generated by tools/generate-sfz-keyswitch-fixture.mjs from the production\n// parser and asset serializer.\n// clang-format off\n' +
    `inline constexpr std::uint32_t kKeyswitchFootprint = ${asset.footprintBytes}u;\n` +
    `inline constexpr std::array<std::uint8_t, ${bytes.length}> kKeyswitchPayload{\n${lines.join('\n')}\n};\n// clang-format on\n`;
  const destination = new URL('../dsp/plugins/others/soundfont_player/keyswitch_fixture.h', import.meta.url);
  if (check) assert.equal((await fs.readFile(destination, 'utf8')).replaceAll('\r\n', '\n'), output);
  else await fs.writeFile(destination, output);
}
if (process.argv[1]?.endsWith('generate-sfz-keyswitch-fixture.mjs')) await generateSfzKeyswitchFixture({ check: process.argv.includes('--check') });

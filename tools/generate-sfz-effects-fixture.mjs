import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { createSfzEffectsAsset, SFZ_EFFECT_ASSET_SOURCES } from '../tests/helpers/sfz-effects-asset-fixture.mjs';

export async function generateSfzEffectsAssetFixture({ check = false } = {}) {
    const destination = new URL('../dsp/plugins/others/soundfont_player/effects_fixture.h', import.meta.url);
    const declarations = [];
    for (const name of Object.keys(SFZ_EFFECT_ASSET_SOURCES)) {
        const asset = await createSfzEffectsAsset(name), bytes = new Uint8Array(asset.payload);
        const lines = [];
        for (let index = 0; index < bytes.length; index += 24)
            lines.push(`  ${[...bytes.subarray(index, index + 24)].join(', ')},`);
        declarations.push(`inline constexpr char kFx${name}Source[] = R"SFZ(${asset.source})SFZ";\n` +
            `inline constexpr std::uint32_t kFx${name}Footprint = ${asset.footprintBytes}u;\n` +
            `inline constexpr std::array<std::uint8_t, ${bytes.length}> kFx${name}Payload{\n${lines.join('\n')}\n};`);
    }
    const output = '#pragma once\n#include <array>\n#include <cstdint>\n' +
        '// Generated by tools/generate-sfz-effects-fixture.mjs from normal SFZ source preparation.\n' +
        '// clang-format off\n' + declarations.join('\n') + '\n// clang-format on\n';
    if (check) assert.equal((await fs.readFile(destination, 'utf8')).replaceAll('\r\n', '\n'), output);
    else await fs.writeFile(destination, output);
}
if (process.argv[1] && pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url)
    await generateSfzEffectsAssetFixture({ check: process.argv.includes('--check') });

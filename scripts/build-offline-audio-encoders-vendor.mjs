import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as esbuild from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDirectory = path.join(root, 'js', 'vendor');
const outfile = path.join(outputDirectory, 'offline-audio-encoders.mjs');
const noticeFile = path.join(outputDirectory, 'offline-audio-encoders.NOTICE.txt');
const libFlacLicenseFile = path.join(root, 'licenses', 'libFLAC-COPYING.Xiph');
const libFlacCommit = '3f1ecff843dd1b8c07fbb5f59425a4ec71fe4f6c';
const mediabunnyVersion = '1.55.7';
const mediabunnyTag = `v${mediabunnyVersion}`;
const mediabunnyCommit = '6319bf2eee41c1143c3de02d35347cf31d6de53e';
const packages = [
  'mediabunny',
  '@mediabunny/flac-encoder'
];

await mkdir(outputDirectory, { recursive: true });
await verifyPinnedVersions();
await esbuild.build({
  stdin: {
    contents: `
      import {
        AudioBufferSource,
        AudioSample,
        AudioSampleSource,
        BufferTarget,
        FlacOutputFormat,
        Output
      } from 'mediabunny';
      import { registerFlacEncoder } from '@mediabunny/flac-encoder';
      registerFlacEncoder();
      export {
        AudioBufferSource,
        AudioSample,
        AudioSampleSource,
        BufferTarget,
        FlacOutputFormat,
        Output
      };
    `,
    resolveDir: root,
    sourcefile: 'offline-audio-encoders-entry.mjs'
  },
  outfile,
  bundle: true,
  format: 'esm',
  platform: 'browser',
  target: 'es2022',
  minify: true,
  sourcemap: false,
  legalComments: 'eof',
  logLevel: 'silent'
});
await writeNotice();

async function readPackage(name) {
  const parts = name.split('/');
  const directory = path.join(root, 'node_modules', ...parts);
  const packageJson = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  const license = (await readFile(path.join(directory, 'LICENSE'), 'utf8')).trim();
  if (!packageJson.version || !packageJson.license || !license) {
    throw new Error(`Incomplete license metadata for ${name}`);
  }
  return { directory, packageJson, license };
}

async function verifyPinnedVersions() {
  const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
  const versions = [];
  for (const name of packages) {
    const dependency = packageJson.dependencies?.[name];
    const installed = (await readPackage(name)).packageJson.version;
    if (dependency !== installed) {
      throw new Error(`${name} must be pinned exactly to installed version ${installed}`);
    }
    versions.push(installed);
  }
  if (new Set(versions).size !== 1) {
    throw new Error('Mediabunny and its encoder extensions must use one version');
  }
  if (versions[0] !== mediabunnyVersion) {
    throw new Error(`Offline audio encoders must use Mediabunny ${mediabunnyVersion}`);
  }
}

async function writeNotice() {
  const sections = [];
  for (const name of packages) {
    const { packageJson, license } = await readPackage(name);
    sections.push([
      name,
      `Version: ${packageJson.version}`,
      `Source tag: ${mediabunnyTag}`,
      `Source commit: ${mediabunnyCommit}`,
      `Source: https://github.com/Vanilagy/mediabunny/tree/${mediabunnyCommit}`,
      `License: ${packageJson.license}`,
      '',
      license
    ].join('\n'));
  }
  const libFlacLicense = (await readFile(libFlacLicenseFile, 'utf8')).trim();
  if (!libFlacLicense) throw new Error('The tracked libFLAC license input is empty');
  sections.push([
    'libFLAC',
    '',
    `Source commit: ${libFlacCommit}`,
    `Source: https://github.com/xiph/flac/tree/${libFlacCommit}`,
    'License file: COPYING.Xiph',
    '',
    libFlacLicense
  ].join('\n'));

  const body = [
    'Third-party notices for js/vendor/offline-audio-encoders.mjs',
    '',
    'Generated by scripts/build-offline-audio-encoders-vendor.mjs.',
    '',
    sections.join('\n\n---\n\n')
  ].join('\n');
  await writeFile(noticeFile, `${body}\n`, 'utf8');
}

import { SFZ_EFFECT_TYPES, SFZ_EFFECT_PARAMETERS, SFZ_EFFECT_BUS, SFZ_EFFECT_LAYOUT } from '../js/sfz/effects.js';

// Consumed by the normal DSP parameter generator, including --check.
export function generateSfzEffectsSchema() {
    const floating = value => {
        if (!Number.isFinite(Math.fround(value))) throw new Error('Invalid SFZ effect schema float.');
        const text = String(value);
        return `${/[.e]/i.test(text) ? text : `${text}.0`}F`;
    };
    const enumeration = (name, entries) => `enum class ${name} : std::uint32_t {\n` +
        entries.map(([key, value]) => `  ${key} = ${value}u,`).join('\n') + '\n};\n';
    const parameters = [], types = [], names = [];
    const nativeName = name => name === 'static' ? 'staticNoise' : name;
    for (const name of Object.keys(SFZ_EFFECT_TYPES)) {
        const definitions = SFZ_EFFECT_PARAMETERS[name];
        types.push(`  {Type::${nativeName(name)}, ${parameters.length}u, ${definitions.length}u},`);
        for (const [index, p] of definitions.entries()) {
            names.push([p.name, index]);
            const options = p.options ? Object.values(p.options) : [];
            const minimum = options.length ? Math.min(...options) : p.min;
            const maximum = options.length ? Math.max(...options) : p.max;
            if (p.default < minimum || p.default > maximum) throw new Error(`Invalid SFZ effect default: ${p.name}`);
            const mask = options.reduce((value, option) => {
                if (!Number.isInteger(option) || option < 0 || option >= 64) throw new Error('Invalid SFZ effect option.');
                return value | 1n << BigInt(option);
            }, 0n);
            parameters.push(`  {Type::${nativeName(name)}, ${index}u, ${floating(p.default)}, ${floating(minimum)}, ` +
                `${floating(maximum)}, ${Boolean(p.options) || p.unit === 'index'}, 0x${mask.toString(16)}ULL},`);
        }
    }
    return '// Generated by scripts/gen-sfz-effects-schema.mjs from js/sfz/effects.js.\n' +
        '// Do not edit this file directly.\n#pragma once\n#include <array>\n#include <cstdint>\n' +
        'namespace effetune::plugins::others::sfz::fxschema {\n' +
        enumeration('Type', Object.entries(SFZ_EFFECT_TYPES).map(([name, id]) => [nativeName(name), id])) +
        enumeration('Bus', Object.entries(SFZ_EFFECT_BUS)) +
        enumeration('Parameter', names) +
        Object.entries(SFZ_EFFECT_LAYOUT).map(([name, value]) => `inline constexpr std::uint32_t k${name} = ${value}u;`).join('\n') +
        '\nstruct TypeSpec {\n  Type type;\n  std::uint32_t firstParameter, parameterCount;\n};\n' +
        'struct ParameterSpec {\n  Type type;\n  std::uint32_t index;\n  float defaultValue, minimum, maximum;\n  bool integer;\n  std::uint64_t options;\n};\n' +
        '// clang-format off\n' +
        `inline constexpr std::array<TypeSpec, ${types.length}> kTypes{{\n${types.join('\n')}\n}};\n` +
        `inline constexpr std::array<ParameterSpec, ${parameters.length}> kParameters{{\n${parameters.join('\n')}\n}};\n` +
        '// clang-format on\n} // namespace effetune::plugins::others::sfz::fxschema\n';
}

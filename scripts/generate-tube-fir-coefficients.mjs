import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import {
  coefficientBits,
  coefficientHash,
  deriveFirCoefficients,
  FIR_COEFFICIENT_ENCODING,
  FIR_DERIVATION
} from '../tests/tools/tube-simulator-lineamp/fir-coefficient-contract.mjs';
import {
  SIX_RATE_CORE,
  SIX_RATE_CORE_SHA256
} from '../tests/tools/tube-simulator-lineamp/generate-stability-manifests.mjs';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const canonicalPath = path.join(
  repoRoot, 'tests', 'fixtures', 'tube-simulator', 'lineamp-v1',
  'fir-coefficients-v1.json'
);
const headerPath = path.join(
  repoRoot, 'dsp', 'plugins', 'saturation', 'tube_simulator',
  'fir_coefficients.generated.h'
);
const javascriptPath = path.join(
  repoRoot, 'plugins', 'saturation', 'tube_simulator.js'
);
const injectionStart = '    // __TUBE_FIR_COEFFICIENTS_INJECT_START__';
const injectionEnd = '    // __TUBE_FIR_COEFFICIENTS_INJECT_END__';

function fail(message) {
  throw new Error(message);
}

function canonicalJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function writeIfChanged(filePath, contents) {
  const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (current === contents) return false;
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, contents, 'utf8');
  return true;
}

function buildCanonicalData() {
  const tables = [];
  const tableByBits = new Map();
  const rates = [];
  for (const config of SIX_RATE_CORE.configs) {
    const coefficients = deriveFirCoefficients(config);
    const bits = coefficientBits(coefficients);
    for (let index = 0; index < bits.length; index++) {
      if (bits[index] !== bits[bits.length - 1 - index]) {
        fail(`${config.sampleRate} Hz FIR derivation is not binary64 symmetric`);
      }
    }
    const halfBits = bits.slice(0, (bits.length + 1) / 2);
    const identity = halfBits.join('');
    let tableId = tableByBits.get(identity);
    const hash = coefficientHash(coefficients);
    if (!tableId) {
      tableId = `fir-${config.firLength}-${hash.slice(0, 16)}`;
      tableByBits.set(identity, tableId);
      tables.push({
        id: tableId,
        firLength: config.firLength,
        halfCoefficientBits: halfBits
      });
    }
    rates.push({
      sampleRate: config.sampleRate,
      firLength: config.firLength,
      tableId,
      coefficientSha256: hash
    });
  }
  return {
    contract: 'tube-fir-coefficients-v1',
    sixRateCoreSha256: SIX_RATE_CORE_SHA256,
    derivation: FIR_DERIVATION,
    coefficientEncoding: FIR_COEFFICIENT_ENCODING,
    storage: 'center-inclusive left half; the right half is its exact mirror',
    rates,
    tables
  };
}

function readCanonicalData(expected, writeCanonical) {
  const expectedText = canonicalJson(expected);
  if (writeCanonical) {
    writeIfChanged(canonicalPath, expectedText);
    return expected;
  }
  if (!fs.existsSync(canonicalPath)) {
    fail('Tube FIR canonical coefficient data is absent');
  }
  const currentText = fs.readFileSync(canonicalPath, 'utf8');
  if (currentText !== expectedText) {
    fail('Tube FIR canonical coefficient data differs from the independent derivation');
  }
  return JSON.parse(currentText);
}

function cppIdentifier(tableId) {
  return `k${tableId.replaceAll(/[^a-z0-9]+/giu, '_')}`;
}

function generateHeader(data) {
  const lines = [
    '#pragma once',
    '',
    '// Generated by scripts/generate-tube-fir-coefficients.mjs. Do not edit.',
    '// clang-format off',
    '',
    '#include <array>',
    '#include <cstddef>',
    '#include <cstdint>',
    '',
    'namespace effetune::dsp::tube_simulator_generated {',
    '',
    'struct FirCoefficientBitsView {',
    '  const std::uint64_t *halfBits;',
    '  std::size_t halfCount;',
    '  std::size_t coefficientCount;',
    '};',
    ''
  ];
  for (const table of data.tables) {
    const name = cppIdentifier(table.id);
    lines.push(
      `inline constexpr std::array<std::uint64_t, ${table.halfCoefficientBits.length}> ${name} = {`
    );
    for (let index = 0; index < table.halfCoefficientBits.length; index += 4) {
      lines.push(`    ${table.halfCoefficientBits.slice(index, index + 4)
        .map(bits => `0x${bits}ULL`).join(', ')},`);
    }
    lines.push('};', '');
  }
  lines.push(
    'inline FirCoefficientBitsView findFirCoefficientBits(double sampleRate) noexcept {'
  );
  for (const rate of data.rates) {
    const name = cppIdentifier(rate.tableId);
    lines.push(
      `  if (sampleRate == ${rate.sampleRate}.0) {`,
      `    return {${name}.data(), ${name}.size(), ${rate.firLength}u};`,
      '  }'
    );
  }
  lines.push(
    '  return {nullptr, 0u, 0u};',
    '}',
    '',
    '} // namespace effetune::dsp::tube_simulator_generated',
    '',
    '// clang-format on',
    ''
  );
  return lines.join('\n');
}

function bitWords(bits) {
  return [`0x${bits.slice(8)}`, `0x${bits.slice(0, 8)}`];
}

function generateJavascriptBlock(data) {
  const lines = [
    injectionStart,
    '    const FIR_COEFFICIENT_TABLES = Object.freeze({'
  ];
  for (const table of data.tables) {
    lines.push(`        '${table.id}': Object.freeze([`);
    const words = table.halfCoefficientBits.flatMap(bitWords);
    for (let index = 0; index < words.length; index += 8) {
      lines.push(`            ${words.slice(index, index + 8).join(', ')},`);
    }
    lines.push('        ]),');
  }
  lines.push(
    '    });',
    '    const FIR_COEFFICIENT_TABLE_BY_RATE = Object.freeze({'
  );
  for (const rate of data.rates) {
    lines.push(`        ${rate.sampleRate}: '${rate.tableId}',`);
  }
  lines.push('    });', injectionEnd);
  return lines.join('\n');
}

function injectJavascript(source, block) {
  const start = source.indexOf(injectionStart);
  const end = source.indexOf(injectionEnd);
  if (start < 0 || end < 0 || end <= start ||
      source.indexOf(injectionStart, start + injectionStart.length) >= 0 ||
      source.indexOf(injectionEnd, end + injectionEnd.length) >= 0) {
    fail('Tube Simulator JavaScript must contain one ordered FIR marker pair');
  }
  return source.slice(0, start) + block +
    source.slice(end + injectionEnd.length);
}

export function runTubeFirGenerator({
  check = false,
  writeCanonical = false
} = {}) {
  if (check && writeCanonical) {
    fail('--check and --write-canonical cannot be combined');
  }
  const expected = buildCanonicalData();
  const canonical = readCanonicalData(expected, writeCanonical);
  const header = generateHeader(canonical);
  const javascript = fs.readFileSync(javascriptPath, 'utf8')
    .replaceAll('\r\n', '\n').replaceAll('\r', '\n');
  const injected = injectJavascript(
    javascript,
    generateJavascriptBlock(canonical)
  );
  const stale = [];
  const outputs = [
    [headerPath, header],
    [javascriptPath, injected]
  ];
  for (const [filePath, contents] of outputs) {
    const current = fs.existsSync(filePath)
      ? fs.readFileSync(filePath, 'utf8')
        .replaceAll('\r\n', '\n').replaceAll('\r', '\n')
      : null;
    if (current === contents) continue;
    stale.push(path.relative(repoRoot, filePath).replaceAll('\\', '/'));
    if (!check) writeIfChanged(filePath, contents);
  }
  return stale;
}

function main() {
  const args = process.argv.slice(2);
  const allowed = new Set(['--check', '--write-canonical']);
  const unknown = args.filter(argument => !allowed.has(argument));
  if (unknown.length !== 0) {
    fail(`unknown argument(s): ${unknown.join(', ')}`);
  }
  const check = args.includes('--check');
  const writeCanonical = args.includes('--write-canonical');
  const stale = runTubeFirGenerator({ check, writeCanonical });
  if (check && stale.length !== 0) {
    fail(`Tube FIR generated outputs are stale: ${stale.join(', ')}`);
  }
  process.stdout.write(
    `${check ? 'Checked' : 'Generated'} Tube FIR canonical coefficients.\n`
  );
}

const isMain = process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url;
if (isMain) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`${error.message}\n`);
    process.exitCode = 1;
  }
}

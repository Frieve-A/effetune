import { SFZ_MOD_KINDS, SFZ_MOD_PROPERTY_IDS, SFZ_MOD_UNITS, SFZ_MOD_SAMPLING,
    SFZ_MOD_PROPERTIES, SFZ_MOD_LAYOUT, SFZ_MOD_SOURCES, SFZ_MOD_FILTER_TYPES, SFZ_MOD_STORAGE,
    SFZ_MOD_VIRTUAL_CONTROLLERS, SFZ_MOD_STORAGE_TYPES, SFZ_MOD_ROUTE_FLAGS } from '../js/sfz/modulation-schema.js';

// A single immutable table is consumed by the JS compiler and native preparer.
// Called by the normal DSP parameter generator, including its --check mode.
export function generateSfzSchema() {
    const enumeration = (name, values) => `enum class ${name} : std::uint32_t {\n${Object.entries(values)
        .map(([key, value]) => `  ${key} = ${value}u,`).join('\n')}\n};`;
    const floating = value => {
        if (!Number.isFinite(Math.fround(value))) throw new Error('Invalid SFZ schema float');
        const text = String(value);
        return `${/[.e]/i.test(text) ? text : `${text}.0`}F`;
    };
    const seen = new Set();
    for (const property of SFZ_MOD_PROPERTIES) {
        const key = `${property.kind}:${property.id}`;
        if (seen.has(key) || property.default < property.min || property.default > property.max ||
            !Object.values(SFZ_MOD_UNITS).includes(property.unit) ||
            !Object.values(SFZ_MOD_UNITS).includes(property.modulationUnit)) throw new Error('Invalid SFZ property definition');
        seen.add(key);
    }
    const names = values => new Map(Object.entries(values).map(([key, value]) => [value, key]));
    const kinds = names(SFZ_MOD_KINDS), units = names(SFZ_MOD_UNITS), sampling = names(SFZ_MOD_SAMPLING), storage = names(SFZ_MOD_STORAGE_TYPES);
    const kindCount = Math.max(...Object.values(SFZ_MOD_KINDS)) + 1;
    const propertyCount = Math.max(...Object.values(SFZ_MOD_PROPERTY_IDS)) + 1;
    const ranks = Array.from({ length: kindCount }, (_, kind) => {
        const row = new Array(propertyCount).fill(255);
        const properties = SFZ_MOD_PROPERTIES.filter(property => property.kind === kind).sort((a, b) => a.id - b.id);
        if (properties.length >= 255) throw new Error('SFZ property rank exceeds its compact representation');
        properties.forEach((property, index) => { row[property.id] = index; });
        return row;
    });
    return `// Generated by scripts/gen-sfz-schema.mjs from js/sfz/modulation-schema.js.\n` +
        `// Do not edit this file directly.\n#pragma once\n#include <array>\n#include <cstdint>\n` +
        `namespace effetune::plugins::others::sfz::schema {\n` +
        [enumeration('Kind', SFZ_MOD_KINDS), enumeration('Property', SFZ_MOD_PROPERTY_IDS),
            enumeration('Unit', SFZ_MOD_UNITS), enumeration('Sampling', SFZ_MOD_SAMPLING),
            enumeration('Source', SFZ_MOD_SOURCES), enumeration('Storage', SFZ_MOD_STORAGE_TYPES), enumeration('RouteFlag', SFZ_MOD_ROUTE_FLAGS), enumeration('FilterType', SFZ_MOD_FILTER_TYPES),
            enumeration('VirtualController', Object.fromEntries(SFZ_MOD_VIRTUAL_CONTROLLERS.map(source => [source.name, source.id])))].join('\n') + '\n' +
        Object.entries(SFZ_MOD_LAYOUT).map(([key, value]) => `inline constexpr std::uint32_t k${key} = ${value}u;`).join('\n') +
        '\n' + Object.entries(SFZ_MOD_STORAGE).map(([key, value]) => `inline constexpr std::uint32_t kStorage${key} = ${value}u;`).join('\n') +
        `\nstruct PropertySpec {\n  Kind kind;\n  Property property;\n  float defaultValue, minimum, maximum;\n` +
        `  Unit unit, modulationUnit;\n  bool integer;\n  std::uint32_t combine;\n  Sampling sampling;\n  Storage storage;\n};\n` +
        `// clang-format off\ninline constexpr std::array<PropertySpec, ${SFZ_MOD_PROPERTIES.length}> kProperties{{\n` +
        SFZ_MOD_PROPERTIES.map(p => `  {Kind::${kinds.get(p.kind)}, Property::${p.name}, ${floating(p.default)}, ` +
            `${floating(p.min)}, ${floating(p.max)}, Unit::${units.get(p.unit)}, Unit::${units.get(p.modulationUnit)}, ` +
            `${p.integer}, ${p.combine}u, Sampling::${sampling.get(p.sampling)}, Storage::${storage.get(p.storage)}},`).join('\n') +
        `\n}};\ninline constexpr std::array<std::array<std::uint8_t, ${propertyCount}>, ${kindCount}> kParameterRanks{{\n` +
        ranks.map(row => `  {{${row.join(',')}}},`).join('\n') +
        `\n}};\n// clang-format on\n` +
        `constexpr std::uint32_t parameterRank(std::uint32_t kind, std::uint32_t property) noexcept {\n` +
        `  if (kind >= ${kindCount}u || property >= ${propertyCount}u)\n    return UINT32_MAX;\n` +
        `  const auto rank = kParameterRanks[kind][property];\n` +
        `  return rank == 255u ? UINT32_MAX : rank;\n}\n` +
        `} // namespace effetune::plugins::others::sfz::schema\n`;
}

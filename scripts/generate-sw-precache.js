const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const esbuild = require('esbuild');

const defaultRoot = path.resolve(__dirname, '..');
const includeRoots = ['css', 'js', 'plugins', 'images', 'presets'];
const explicit = [
  'effetune.html',
  'remote.html',
  'features/effetune-benchmark.js',
  'features/effetune-benchmark-score.js',
  'features/benchmark-score-reference.js',
  'features/measurement/dataStorage.js',
  'features/measurement/measurement-model.js',
  'features/measurement/audio-utils/channel-selection.js',
  'features/measurement/audio-utils/output-routing.js',
  'features/measurement/peq-calculator/design-utils.js',
  'features/measurement/peq-calculator/filter-response.js',
  'features/measurement/peq-calculator/optimization.js',
  'features/measurement/peq-calculator/peak-detection.js',
  'features/measurement/peq-calculator/peq-calculator.js',
  'features/measurement/peq-calculator/smoothing.js',
  'features/measurement/ui/peq-clipboard.js',
  'manifest.json',
  'LICENSE',
  'js/vendor/sqlite/LICENSE.md',
  'js/audio/dsd/dsd-kernels.c',
  'js/audio/dsd/dst-decoder.c',
  'scripts/build-dsd-wasm.mjs',
  'package.json',
  'sw.js',
  'plugins/plugins.txt'
];
const allowedExtensions = new Set(['.js', '.mjs', '.css', '.json', '.json5', '.png', '.ico', '.jpg', '.jpeg', '.svg', '.txt', '.wasm', '.woff2', '.effetune_preset']);
const binaryExtensions = new Set(['.ico', '.jpeg', '.jpg', '.png', '.wasm', '.woff2']);
const excludedPathPatterns = [
  /^images\/_vizaudio_tmp\//,
  /^images\/screenshot(?:-[^/]+)?\.png$/,
  /^images\/ogp\.jpg$/,
  /^images\/video_thumbnail\.jpg$/,
  /^plugins\/dsp\/effetune-dsp\.debug\.wasm$/
];

// The application module that js/startup.js imports; its static graph is preloaded by the app shell.
const startupEntry = 'js/app.js';
const appShell = 'effetune.html';
const preloadStartMarker = '<!-- Module preloads generated by npm run assets:web from the static import graph of js/app.js. -->';
const preloadEndMarker = '<!-- End of generated module preloads. -->';

function shouldPrecache(relativePath) {
  return !excludedPathPatterns.some(pattern => pattern.test(relativePath));
}

function walk(root, dir, output) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      walk(root, fullPath, output);
    } else if (allowedExtensions.has(path.extname(entry.name).toLowerCase())) {
      const relativePath = path.relative(root, fullPath).replace(/\\/g, '/');
      if (shouldPrecache(relativePath)) {
        output.add(relativePath);
      }
    }
  }
}

function collectPrecacheUrls(root = defaultRoot) {
  const urls = new Set(explicit);
  for (const dir of includeRoots) {
    walk(root, path.join(root, dir), urls);
  }
  return [...urls].sort();
}

function readPackageJson(root = defaultRoot) {
  return JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
}

function createPrecacheDigest(root, urls) {
  const hash = crypto.createHash('sha256');
  for (const relativePath of urls) {
    let contents = fs.readFileSync(path.join(root, relativePath));
    if (!binaryExtensions.has(path.extname(relativePath).toLowerCase())) {
      contents = Buffer.from(contents.toString('utf8').replace(/\r\n?/g, '\n'));
    }
    hash.update(`${relativePath.length}:${relativePath}\n`);
    hash.update(`${contents.length}:`);
    hash.update(contents);
    hash.update('\n');
  }
  return hash.digest('hex');
}

function staticImports(root, file) {
  // Parse with esbuild and keep every import external, so only this module is analyzed.
  const { metafile } = esbuild.buildSync({
    absWorkingDir: root,
    entryPoints: [file],
    bundle: true,
    external: ['*'],
    format: 'esm',
    logLevel: 'silent',
    metafile: true,
    write: false
  });
  return metafile.inputs[file].imports
    .filter(entry => entry.kind === 'import-statement')
    .map(({ path: specifier }) => {
      if (!specifier.startsWith('.')) throw new Error(`${file} has an unsupported static import: ${specifier}`);
      return path.posix.normalize(path.posix.join(path.posix.dirname(file), specifier));
    });
}

// Static imports and re-exports only: dynamic import() targets load on demand and are not preloaded.
function collectStartupModules(root = defaultRoot) {
  const modules = new Set();
  const visit = file => {
    if (modules.has(file)) return;
    modules.add(file);
    staticImports(root, file).forEach(visit);
  };
  visit(startupEntry);
  return [...modules].sort();
}

function buildAppShellHtml(root = defaultRoot) {
  const source = fs.readFileSync(path.join(root, appShell), 'utf8');
  const start = source.indexOf(preloadStartMarker);
  const end = source.indexOf(preloadEndMarker, start);
  if (start < 0 || end < 0) throw new Error(`${appShell} is missing the generated module preload markers`);
  const indent = source.slice(source.lastIndexOf('\n', start) + 1, start);
  const links = collectStartupModules(root)
    .map(file => `${indent}<link rel="modulepreload" href="${file}">\n`)
    .join('');
  return `${source.slice(0, start)}${preloadStartMarker}\n${links}${indent}${source.slice(end)}`;
}

function writeIfChanged(filePath, contents) {
  if (!fs.existsSync(filePath) || fs.readFileSync(filePath, 'utf8') !== contents) fs.writeFileSync(filePath, contents);
}

function assertFresh(root, filePath, expected) {
  const actual = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (actual !== expected) {
    const relativePath = path.relative(root, filePath).replace(/\\/g, '/');
    throw new Error(`${relativePath} is stale; run npm run assets:web`);
  }
}

function buildPrecacheSource({ root = defaultRoot, packageJson = readPackageJson(root) } = {}) {
  const urls = collectPrecacheUrls(root);
  const digest = createPrecacheDigest(root, urls);
  const cacheVersion = `effetune-v${packageJson.version}-${digest.slice(0, 16)}`;
  const integrity = Object.fromEntries(urls.map(url => [
    `./${url}`,
    `sha256-${crypto.createHash('sha256').update(fs.readFileSync(path.join(root, url))).digest('base64')}`
  ]));
  // sw.js is a classic script, so it receives the DSP loader's SIMD probe as data.
  const { SIMD_PROBE_BYTES } = require(path.join(root, 'js/audio/dsp-wasm-loader.js'));
  const body = [
    `self.EFFECTUNE_CACHE_VERSION = ${JSON.stringify(cacheVersion)};`,
    `self.EFFECTUNE_PRECACHE_URLS = ${JSON.stringify(urls.map(url => `./${url}`), null, 2)};`,
    `self.EFFECTUNE_PRECACHE_INTEGRITY = ${JSON.stringify(integrity, null, 2)};`,
    `self.EFFECTUNE_SIMD_PROBE_BYTES = ${JSON.stringify([...SIMD_PROBE_BYTES])};`,
    ''
  ].join('\n');

  return {
    body,
    cacheVersion,
    digest,
    integrity,
    urls
  };
}

// The app shell is written first because its bytes are part of the precache integrity.
function generatePrecache({ root = defaultRoot, outputPath = path.join(root, 'sw-precache.js') } = {}) {
  writeIfChanged(path.join(root, appShell), buildAppShellHtml(root));
  const result = buildPrecacheSource({ root });
  fs.writeFileSync(outputPath, result.body);
  return result;
}

function checkPrecache({ root = defaultRoot, outputPath = path.join(root, 'sw-precache.js') } = {}) {
  assertFresh(root, path.join(root, appShell), buildAppShellHtml(root));
  const result = buildPrecacheSource({ root });
  assertFresh(root, outputPath, result.body);
  return result;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const unknown = args.filter(argument => argument !== '--check');
  if (unknown.length > 0) {
    console.error(`Unknown argument(s): ${unknown.join(', ')}`);
    process.exitCode = 1;
  } else {
    try {
      if (args.includes('--check')) {
        checkPrecache();
      } else {
        generatePrecache();
      }
    } catch (error) {
      console.error(error.message);
      process.exitCode = 1;
    }
  }
}

module.exports = {
  buildAppShellHtml,
  buildPrecacheSource,
  checkPrecache,
  collectPrecacheUrls,
  collectStartupModules,
  createPrecacheDigest,
  generatePrecache
};

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sourceDirectory = path.join(root, 'js', 'audio', 'dsd');
const outputPath = path.join(sourceDirectory, 'dsd-wasm.generated.js');
const compilerVersion = '6.0.13';
const sources = ['dsd-kernels.c', 'dst-decoder.c'];
const exports = ['dsd_decimate_bits', 'dsd_decimate_pcm', 'dsd_resample', 'dst_decode'];
const flags = ['--target=wasm32', '-std=c11', '-O3', '-ffreestanding', '-nostdlib',
  '-fno-builtin', '-ffp-contract=off', '-fno-fast-math', '-msimd128', '-Wall', '-Wextra', '-Werror',
  '-Wl,--no-entry', '-Wl,--export-memory', '-Wl,--export=__heap_base',
  '-Wl,-z,stack-size=65536', '-Wl,--initial-memory=131072', '-Wl,--max-memory=20971520',
  ...exports.map(name => `-Wl,--export=${name}`)];

function inputDigest() {
  const hash = crypto.createHash('sha256');
  for (const file of [...sources.map(name => path.join(sourceDirectory, name)), fileURLToPath(import.meta.url)]) {
    hash.update(fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n'));
  }
  return hash.digest('hex');
}

export function checkDsdWasm() {
  const source = fs.readFileSync(outputPath, 'utf8');
  if (!source.includes(`Input SHA-256: ${inputDigest()}`)) {
    throw new Error('DSD WebAssembly is stale. Run npm run build:dsd with Emscripten 6.0.13.');
  }
}

function run(command, args) {
  const result = spawnSync(command, args, { cwd: root, encoding: 'utf8', windowsHide: true });
  if (result.error || result.status !== 0) {
    throw new Error(result.error?.message || `${command} failed:\n${result.stdout}${result.stderr}`);
  }
  return result.stdout;
}

function build() {
  const sdk = path.resolve(process.env.EMSDK || path.join(root, '.emsdk'));
  const extension = process.platform === 'win32' ? '.exe' : '';
  const version = run(path.join(sdk, 'upstream', 'emscripten', `emcc${extension}`), ['--version']);
  if (!version.includes(` ${compilerVersion} `)) throw new Error(`Expected Emscripten ${compilerVersion}`);
  const directory = path.join(root, 'out', 'dsd-decoder');
  fs.mkdirSync(directory, { recursive: true });
  const binary = path.join(directory, 'dsd-decoder.wasm');
  run(path.join(sdk, 'upstream', 'bin', `clang${extension}`),
    [...flags, ...sources.map(name => path.join(sourceDirectory, name)), '-o', binary]);
  const bytes = fs.readFileSync(binary);
  const module = new WebAssembly.Module(bytes);
  if (WebAssembly.Module.imports(module).length !== 0) throw new Error('DSD module must have no runtime imports');
  const names = WebAssembly.Module.exports(module).map(entry => entry.name);
  if (!['memory', '__heap_base', ...exports].every(name => names.includes(name))) throw new Error('Invalid DSD WASM exports');
  const generated = `// Generated by scripts/build-dsd-wasm.mjs; Emscripten ${compilerVersion}.\n` +
    `// Input SHA-256: ${inputDigest()}\n` +
    '// Includes LGPL-2.1-or-later DST code; see dst-decoder.NOTICE.txt and dst-decoder.LICENSE.txt.\n' +
    `export const DSD_WASM_BASE64 = '${bytes.toString('base64')}';\n`;
  if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== generated) fs.writeFileSync(outputPath, generated);
  console.log(`Built DSD WebAssembly (${bytes.length} bytes, no runtime imports).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) checkDsdWasm();
  else build();
}
